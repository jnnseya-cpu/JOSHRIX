/**
 * /api/blog-agent — the JOSHRIX Content Agent: SEO blog on autopilot.
 *   GET  ?public=1            → published post index (public, for /blog + admin)
 *   GET  (cron / admin key)   → autopilot: pick the next editorial topic, write
 *                               with Claude, publish. Wired to Vercel Cron.
 *   POST { topic? }           → admin: write & publish a post now (custom topic)
 * Auth for generation: x-admin-key === MODERATION_KEY, or the Vercel Cron
 * Authorization: Bearer CRON_SECRET header. Fail closed otherwise.
 * Every post ships with meta description, keywords, internal links to live
 * pages/games (dynamic linking), and ready-to-paste social captions.
 */
